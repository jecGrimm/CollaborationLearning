import sys
import csv
import json
from collections import Counter
from itertools import combinations
from pathlib import Path

import matplotlib.pyplot as plt

N_SENT = 5

#read csv file
def load_rows(csv_path):
    with open(csv_path, newline="", encoding="utf-8") as file:
        reader = csv.DictReader(file)
        rows = list(reader)

    for r in rows:
        r["id"] = int(r["id"])

        gold = json.loads(r["correct_order"])                  
        answer = json.loads(r["order"])[0]["ranker"]["order"]  

        r["correct"] = answer == gold                          
        r["pos_correct"] = [answer[i] == gold[i] for i in range(N_SENT)]

       
        r["wrong_pos"] = [i + 1 for i in range(N_SENT) if answer[i] != gold[i]]

    return rows


#Overall Accuracy (exact match)
def plot_overall_accuracy(rows, ax):
    correct = sum(r["correct"] for r in rows)
    wrong = len(rows) - correct
    values = [correct, wrong]

    bars = ax.bar(["Correct", "Incorrect"], values)
    ax.set_title(f"Overall accuracy, exact match (n={len(rows)})")
    ax.set_ylabel("Number of tasks")
    ax.set_ylim(0, max(values) * 1.2)
    for b in bars:
        h = b.get_height()
        ax.annotate(f"{h}\n({h/len(rows):.0%})", (b.get_x() + b.get_width() / 2, h),
                    ha="center", va="bottom")


#Accuracy per Position
def plot_position_accuracy(rows, ax):
    n = len(rows)
    hits = [sum(r["pos_correct"][i] for r in rows) for i in range(N_SENT)]
    rates = [h / n for h in hits]

    bars = ax.bar([f"Pos {i + 1}" for i in range(N_SENT)], rates)
    ax.set_title("Accuracy per position")
    ax.set_ylabel("Proportion correct")
    ax.set_ylim(0, 1.15)
    for b, h, rt in zip(bars, hits, rates):
        ax.annotate(f"{rt:.0%}\n({h}/{n})", (b.get_x() + b.get_width() / 2, rt),
                    ha="center", va="bottom")


#Swapped Position Pairs
def plot_swapped_pairs(rows, ax):
    counter = Counter()
    for r in rows:
        for pair in combinations(r["wrong_pos"], 2):
            counter[pair] += 1

    pairs = list(combinations(range(1, N_SENT + 1), 2))
    labels = [f"{a}-{b}" for a, b in pairs]
    values = [counter.get(p, 0) for p in pairs]
    colors = ["tab:red" if b - a == 1 else "tab:gray" for a, b in pairs]

    bars = ax.bar(labels, values, color=colors)
    ax.set_title("Most frequently swapped position pairs\n(red = adjacent)")
    ax.set_xlabel("Position pair")
    ax.set_ylabel("Number of swaps")
    ax.set_ylim(0, max(values) * 1.2)
    for b, v in zip(bars, values):
        ax.annotate(str(v), (b.get_x() + b.get_width() / 2, v),
                    ha="center", va="bottom")


#save plots
def main():
    if len(sys.argv) > 1:
        csv_path = Path(sys.argv[1])
    else:
        csv_path = Path(__file__).parent / "annotated_ROCStories_150.csv"

    if not csv_path.exists():
        sys.exit(f"CSV file not found: {csv_path}\n"
                  f"Pass the path explicitly: python {sys.argv[0]} <path_to_csv>")

    rows = load_rows(csv_path)

    fig, axes = plt.subplots(1, 3, figsize=(18, 6.5))
    plot_overall_accuracy(rows, axes[0])
    plot_position_accuracy(rows, axes[1])
    plot_swapped_pairs([r for r in rows if not r["correct"]], axes[2])

    out_path = csv_path.with_name("rocstories_visualizations.png")
    fig.savefig(out_path, dpi=150, bbox_inches="tight")
    print(f"\nSaved charts to: {out_path}")
    plt.show()


if __name__ == "__main__":
    main()
    
