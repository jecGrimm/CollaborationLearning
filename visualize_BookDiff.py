import sys
import csv
import json
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt

#read csv file
def load_rows(csv_path):
    with open(csv_path, newline="", encoding="utf-8") as file:
        reader = csv.DictReader(file)
        rows = list(reader)

    for r in rows:
        r["id"] = int(r["id"])
        r["correct"] = r["gold_title"] == r["different_genre"]
        r["lead_time_f"] = float(r["lead_time"])

        titles = json.loads(r["titles"])
        summaries = json.loads(r["summaries"])
        lengths = dict(zip(titles, (len(s.split()) for s in summaries)))
        r["gold_is_shortest"] = lengths[r["gold_title"]] == min(lengths.values())
        r["gold_is_longest"] = lengths[r["gold_title"]] == max(lengths.values())

    return rows


#Overall Acuraccy
def plot_overall_accuracy(rows, ax):
    correct = sum(r["correct"] for r in rows)
    wrong = len(rows) - correct
    values = [correct, wrong]

    bars = ax.bar(["Correct", "Incorrect"], values)
    ax.set_title(f"Overall accuracy (n={len(rows)})")
    ax.set_ylabel("Number of tasks")
    ax.set_ylim(0, max(values) * 1.2)  
    for b in bars:
        h = b.get_height()
        ax.annotate(f"{h}\n({h/len(rows):.0%})", (b.get_x() + b.get_width() / 2, h),
                    ha="center", va="bottom")

#Genre Error Rate
def plot_genre_error_rate(rows, ax, min_n=5):
    stats = defaultdict(lambda: [0, 0])  # genre -> [wrong, total]
    for r in rows:
        g = r["same_genre"]
        stats[g][1] += 1
        if not r["correct"]:
            stats[g][0] += 1

    filtered = {g: (w, t) for g, (w, t) in stats.items() if t >= min_n}
    items = sorted(filtered.items(), key=lambda kv: -kv[1][0] / kv[1][1])

    labels = [f"{g}\n({w}/{t})" for g, (w, t) in items]
    rates = [w / t for g, (w, t) in items]

    ax.bar(labels, rates)
    ax.set_title(f"Error rate per genre (n >= {min_n})")
    ax.set_ylabel("Error rate")
    ax.set_ylim(0, 1)
    ax.tick_params(axis="x", rotation=45)
    for lbl in ax.get_xticklabels():
        lbl.set_ha("right")

#Lenght of Summaries bias
def plot_length_bias(rows, ax):
    n = len(rows)
    shortest = sum(r["gold_is_shortest"] for r in rows)
    longest = sum(r["gold_is_longest"] for r in rows)
    middle = n - shortest - longest
    values = [shortest, longest, middle]

    labels = ["Gold = shortest", "Gold = longest", "Gold = middle"]

    bars = ax.bar(labels, values)
    ax.set_ylim(0, max(values) * 1.25)
    ax.axhline(n / 3, color="gray", linestyle="--", linewidth=1,
               label=f"Chance level (n/3 = {n/3:.1f})")
    ax.set_title("Does summary length predict the gold label?")
    ax.set_ylabel("Number of tasks")
    ax.legend()
    for b, v in zip(bars, values):
        ax.annotate(f"{v}\n({v/n:.0%})", (b.get_x() + b.get_width() / 2, v),
                    ha="center", va="bottom")


#save plots
def main():
    if len(sys.argv) > 1:
        csv_path = Path(sys.argv[1])
    else:
        csv_path = Path(__file__).parent / "annotated_BookDiff_150.csv"

    if not csv_path.exists():
        sys.exit(f"CSV file not found: {csv_path}\n"
                  f"Pass the path explicitly: python {sys.argv[0]} <path_to_csv>")

    rows = load_rows(csv_path)

    fig, axes = plt.subplots(1, 3, figsize=(18, 6.5))
    plot_overall_accuracy(rows, axes[0])
    plot_genre_error_rate(rows, axes[1])
    plot_length_bias(rows, axes[2])

    out_path = csv_path.with_name("bookdiff_visualizations.png")
    fig.savefig(out_path, dpi=150, bbox_inches="tight")
    print(f"\nSaved charts to: {out_path}")
    plt.show()


if __name__ == "__main__":
    main()

