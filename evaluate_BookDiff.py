import sys
import csv
from collections import defaultdict


def evaluate(path):
    rows = []
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            gold = row["gold_title"].strip()
            picked = row["different_genre"].strip()
            if not gold or not picked:
                print(f"Skipping annotation {row.get('annotation_id')}: "
                      f"missing gold_title or different_genre")
                continue
            rows.append({
                "annotation_id": row.get("annotation_id"),
                "annotator": row.get("annotator", "unknown"),
                "titles": row.get("titles"),
                "gold": gold,
                "picked": picked,
                "correct": gold == picked,
            })
    return rows


def report(rows):
    total = len(rows)
    correct = sum(1 for r in rows if r["correct"])
    accuracy = correct / total if total else 0.0

    print(f"Total annotations: {total}")
    print(f"Correct: {correct}")
    print(f"Accuracy: {accuracy:.2%}")

    by_annotator = defaultdict(list)
    for r in rows:
        by_annotator[r["annotator"]].append(r)

    if len(by_annotator) > 1:
        print("\nPer annotator:")
        for annotator, ann_rows in by_annotator.items():
            c = sum(1 for r in ann_rows if r["correct"])
            n = len(ann_rows)
            print(f"  {annotator}: {c}/{n} ({c/n:.2%})")

    mistakes = [r for r in rows if not r["correct"]]
    if mistakes:
        print(f"\nMismatches ({len(mistakes)}):")
        for r in mistakes:
            print(f"  annotation {r['annotation_id']}: "
                  f"picked='{r['picked']}' gold='{r['gold']}' "
                  f"options={r['titles']}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print("Usage: python evaluate_annotations.py <file.csv>")
        sys.exit(1)

    rows = evaluate(sys.argv[1])
    report(rows)

