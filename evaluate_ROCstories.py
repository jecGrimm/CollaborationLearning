import csv, json
import sys

def evaluate(path):
    rows = []
    with open(path, newline="") as file:
        reader = csv.DictReader(file)
        for row in reader:
            gold = json.loads(row["correct_order"])
            raw_order = json.loads(row["order"])
            picked = raw_order[0]["ranker"]["order"]

            rows.append({
                "annotation_id": row.get("annotation_id"),
                "annotator": row.get("annotator", "unknown"),
                "storyid": row.get("storyid"),
                "storytitle": row.get("storytitle"),
                "lead_time": row.get("lead_time"),
                "gold": gold,
                "picked": picked,
                "correct": gold == picked,
            })
    return rows


def report(rows):
    total = len(rows)
    correct = sum(r["correct"] for r in rows)
    accuracy = correct / total if total else 0

    print(f"Total Annotation: {total}")
    print(f"Correct: {correct}")
    print(f"Accuracy: {accuracy:.2%}")
    print()
    print("Incorrect:")
    for r in rows:
        if not r["correct"]:
            print(f"- {r['storytitle']} (id {r['storyid']})")
            print(f"    gold:   {r['gold']}")
            print(f"    picked: {r['picked']}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print("Usage: python evaluate.py <file.csv>")
        sys.exit(1)

    path = sys.argv[1]
    results = evaluate(path)
    report(results)

