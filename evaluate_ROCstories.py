import csv, json
import sys


def position_accuracy(gold, picked):
    if not gold:
        return 0.0
    correct_pos = sum(g == p for g, p in zip(gold, picked))
    return correct_pos / len(gold)


def evaluate(path):
    rows = []
    with open(path, newline="") as file:
        reader = csv.DictReader(file)
        for row in reader:
            gold = json.loads(row["correct_order"])
            raw_order = json.loads(row["order"])
            picked = raw_order[0]["ranker"]["order"]

            rows.append({
                "annotation_id": row.get("annotation_id"),
                "annotator": row.get("annotator", "unknown"),
                "storyid": row.get("storyid"),
                "storytitle": row.get("storytitle"),
                "lead_time": row.get("lead_time"),
                "gold": gold,
                "picked": picked,
                "correct": gold == picked,  
                "pos_acc": position_accuracy(gold, picked),
            })
    return rows


def report(rows):
    total = len(rows)

    accuracy = sum(r["pos_acc"] for r in rows) / total if total else 0

    # For reference only: exact match accuracy
    exact = sum(r["correct"] for r in rows)
    exact_acc = exact / total if total else 0

    print(f"Total Annotation: {total}")
    print(f"Accuracy (avg. fraction of sentences at correct position): {accuracy:.2%}")
    print(f"Fully correct orders: {exact} ({exact_acc:.2%})")
    print()
    print("Not fully correct:")
    for r in rows:
        if not r["correct"]:
            print(f"- {r['storytitle']} (id {r['storyid']}) - {r['pos_acc']:.0%} in correct position")
            print(f"    gold:   {r['gold']}")
            print(f"    picked: {r['picked']}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print("Usage: python evaluate_ROCstories.py <file.csv>")
        sys.exit(1)

    path = sys.argv[1]
    results = evaluate(path)
    report(results)

